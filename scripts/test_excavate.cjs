/* Run against the local static server. Blocks analytics; stores QA files locally. */
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.argv[2] || 'http://127.0.0.1:8765';
const output=path.resolve(__dirname,'../.local-preview'); fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const errors=[], checks=[];
  const check=s=>{checks.push(s);console.log('PASS '+s);};
  const context=await browser.newContext({viewport:{width:1360,height:1000}});
  await context.route(/google-analytics\.com|googletagmanager\.com/,r=>r.abort());
  const page=await context.newPage(); page.on('pageerror',e=>errors.push(e.message));
  const ready=()=>page.locator('#digBrush').waitFor();
  const uncover=async()=>{for(let i=0;i<20 && await page.locator('#digLift').isDisabled();i++) await page.locator('#digBrush').click(); assert(await page.locator('#digLift').isEnabled());};
  try{
    await page.goto(base+'/excavate.html'); await ready();
    await page.screenshot({path:path.join(output,'excavate-desktop.png'),fullPage:true});
    assert.equal(await page.locator('#digCount').textContent(),'0 / 128');
    const bounds=await page.locator('#digSand').boundingBox();
    const before=Number(await page.locator('.dig-progress').getAttribute('aria-valuenow'));
    await page.mouse.move(bounds.x+bounds.width*.4,bounds.y+bounds.height*.4); await page.mouse.down();
    await page.mouse.move(bounds.x+bounds.width*.65,bounds.y+bounds.height*.65,{steps:16}); await page.mouse.up();
    assert(Number(await page.locator('.dig-progress').getAttribute('aria-valuenow'))>before);check('Mouse drag reveals artwork immediately');
    await page.screenshot({path:path.join(output,'excavate-partial.png'),fullPage:true});
    await uncover(); await page.locator('#digLift').click();
    assert(await page.locator('#digResult').isVisible());
    const href=await page.locator('#digLink').getAttribute('href');
    const number=Number(href.match(/(\d+)\.html/)[1]);
    const eps=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../data/search.json'))).episodes;
    assert.equal(await page.locator('#digTitle').textContent(),eps.find(e=>e.number===number).title);
    assert.equal(await page.locator('#digResultImage').getAttribute('src'),eps.find(e=>e.number===number).image);
    assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('takitsubo:excavation:v1'))),[number]);
    check('Correct episode title/artwork/link and saved discovery');
    await page.screenshot({path:path.join(output,'excavate-result.png'),fullPage:true});
    await page.evaluate(()=>{window.originalAudio=document.querySelector('audio');window.docMarker=true;});
    await page.locator('#digLink').click(); await page.waitForURL('**/'+href);
    await page.waitForFunction(()=>document.querySelector('#tkPlayer'));
    assert(await page.evaluate(()=>window.docMarker && window.originalAudio===document.querySelector('audio')));
    assert.equal(await page.locator('link[href*="excavate.css"]').count(),0);
    await page.goBack(); await ready(); assert.equal(await page.locator('#digCount').textContent(),'1 / 128');
    assert.equal(await page.locator('link[href*="excavate.css"]').count(),1);
    check('Internal navigation/back retains audio element, cleans CSS and restores collection');
    await page.reload(); await ready(); assert.equal(await page.locator('#digCount').textContent(),'1 / 128');
    await page.locator('.dig-collection-toggle').click(); assert.equal(await page.locator('.dig-entry').count(),1);
    check('Collection survives reload and opens episode links');
    await page.setViewportSize({width:390,height:844}); await page.locator('#digBrush').scrollIntoViewIfNeeded();
    await page.locator('#digBrush').focus(); await page.keyboard.press('Enter'); await uncover(); await page.locator('#digLift').click();
    await page.screenshot({path:path.join(output,'excavate-mobile-result.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('#digNext').click(); assert(await page.locator('#digLift').isDisabled());
    await page.screenshot({path:path.join(output,'excavate-mobile.png'),fullPage:true});
    check('Mobile layout, keyboard excavation, next round without wait');
    const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
    await mobile.route(/google-analytics\.com|googletagmanager\.com/,r=>r.abort());
    await mobile.addInitScript(()=>localStorage.setItem('takitsubo:excavation:v1','{"invalid":true}'));
    const mp=await mobile.newPage(); mp.on('pageerror',e=>errors.push(e.message));
    await mp.goto(base+'/excavate.html');await mp.locator('#digBrush').waitFor();
    const mb=await mp.locator('#digSand').boundingBox();const bp=Number(await mp.locator('.dig-progress').getAttribute('aria-valuenow'));
    await mp.touchscreen.tap(mb.x+mb.width*.5,mb.y+mb.height*.5);
    assert(Number(await mp.locator('.dig-progress').getAttribute('aria-valuenow'))>bp);
    check('Real touch input, reduced motion and malformed saved-data recovery');
    await mobile.close();
    const failure=await browser.newContext();
    await failure.route(/google-analytics\.com|googletagmanager\.com/,r=>r.abort());
    const fp=await failure.newPage();await fp.route('**/data/search.json*',r=>r.abort());
    await fp.goto(base+'/excavate.html');await fp.getByRole('button',{name:'もう一度読み込む'}).waitFor();
    check('Data load failure provides retry');await failure.close();
    const blocked=await browser.newContext({viewport:{width:390,height:844}});
    await blocked.route(/google-analytics\.com|googletagmanager\.com/,r=>r.abort());
    await blocked.addInitScript(()=>{
      Storage.prototype.getItem=function(){throw new Error('storage disabled');};
      Storage.prototype.setItem=function(){throw new Error('storage disabled');};
    });
    const sp=await blocked.newPage();sp.on('pageerror',e=>errors.push(e.message));
    await sp.route('**/assets/img/ep/*',r=>r.abort());
    await sp.goto(base+'/excavate.html');await sp.locator('#digBrush').waitFor();
    for(let i=0;i<20 && await sp.locator('#digLift').isDisabled();i++) await sp.locator('#digBrush').click();
    await sp.locator('#digLift').click();
    assert(await sp.locator('#digResult').isVisible());assert((await sp.locator('#digSaveNote').textContent()).includes('保存を利用できない'));
    check('Storage and artwork failure still allow excavation and episode navigation');await blocked.close();
    await page.goto(base+'/episodes/122.html');await page.locator('.tkp-play').click();
    await page.waitForFunction(()=>document.querySelector('audio').currentTime>2,null,{timeout:60000});
    await page.evaluate(()=>{
      window.excavationAudio=document.querySelector('audio');window.excavationTime=excavationAudio.currentTime;window.excavationEvents=[];
      ['pause','emptied','loadstart','error'].forEach(type=>excavationAudio.addEventListener(type,()=>excavationEvents.push(type)));
    });
    await page.locator('.footer-nav a[href$="excavate.html"]').click();await ready();
    await uncover();await page.locator('#digLift').click();
    assert(await page.evaluate(()=>document.querySelector('audio')===excavationAudio && !excavationAudio.paused && excavationAudio.currentTime>excavationTime && !excavationEvents.length));
    // Scrolling must make the CTA reachable above the persistent mini player.
    await page.locator('#digLink').scrollIntoViewIfNeeded();
    assert(await page.locator('#digLink').isVisible());
    check('Remote audio keeps playing while entering and excavating on mobile');
    assert.deepEqual(errors,[]);check('No JavaScript errors');
  } finally {
    fs.writeFileSync(path.join(output,'excavate-report.json'),JSON.stringify({checks,errors},null,2));
    await browser.close();
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
